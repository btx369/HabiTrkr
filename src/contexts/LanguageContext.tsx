const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

interface LanguageProviderProps {
  children: ReactNode;
}

export function LanguageProvider({ children }: LanguageProviderProps) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = getLocalStorageString(LANGUAGE_KEY, 'en');
    const validLanguages: Language[] = ['en', 'pt', 'es', 'fr', 'de', 'it', 'nl', 'pl', 'tr', 'ja', 'zh', 'ko'];
    return validLanguages.includes(saved as Language) ? (saved as Language) : 'en';
  });

  const handleSetLanguage = (newLanguage: Language) => {
    setLanguage(newLanguage);
    setLocalStorageString(LANGUAGE_KEY, newLanguage);
  };

  /**
   * Resolves a key for the active language, falling back to English.
   *
   * The fallback matters more than it looks. Every language is complete today, but a key
   * added later reaches the other languages only when they are translated; without this
   * they would render the KEY itself on screen ("tabFolders" instead of "Folders").
   * Falling back to English keeps them readable until then.
   *
   * The key is returned only when even English lacks it, which means a typo in a call
   * site shows up as the key name instead of silently rendering nothing.
   */
  // Stable until the language changes. Anything memoised on `t` (the toast helpers,
  // effects that announce with a toast) used to be rebuilt on every render because this
  // was a new function each time.
  const t = useCallback((key: string): string => {
    const forLanguage = translations[language] as Record<string, string | undefined>;
    const forEnglish = translations.en as Record<string, string | undefined>;
    return forLanguage[key] ?? forEnglish[key] ?? key;
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage: handleSetLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
